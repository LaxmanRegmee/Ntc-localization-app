-- Helper function for updating timestamps
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Function to record complaint status changes
CREATE OR REPLACE FUNCTION record_complaint_status_change()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO complaint_status_history 
            (complaint_id, old_status, new_status, changed_by)
        VALUES 
            (NEW.id, OLD.status, NEW.status, auth.uid());
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Helper function to create enum if not exists
CREATE OR REPLACE FUNCTION create_complaint_status_enum()
RETURNS void AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'complaint_status') THEN
        CREATE TYPE complaint_status AS ENUM ('open', 'in_progress', 'resolved', 'closed');
    END IF;
END;
$$ LANGUAGE plpgsql;

-- Initialize complaint system
CREATE OR REPLACE FUNCTION initialize_complaint_system()
RETURNS void AS $$
DECLARE
    policy_exists boolean;
BEGIN
    -- Create enum type
    PERFORM create_complaint_status_enum();

    -- Create complaints table if not exists
    CREATE TABLE IF NOT EXISTS complaints (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
        user_id UUID NOT NULL,
        subject TEXT NOT NULL,
        description TEXT NOT NULL,
        status complaint_status DEFAULT 'open' NOT NULL,
        updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
    );

    -- Create responses table if not exists
    CREATE TABLE IF NOT EXISTS complaint_responses (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        complaint_id BIGINT REFERENCES complaints(id) ON DELETE CASCADE,
        created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
        response_text TEXT NOT NULL,
        responded_by UUID
    );

    -- Create status history table if not exists
    CREATE TABLE IF NOT EXISTS complaint_status_history (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        complaint_id BIGINT REFERENCES complaints(id) ON DELETE CASCADE,
        created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
        old_status complaint_status,
        new_status complaint_status NOT NULL,
        changed_by UUID
    );

    -- Create indexes
    CREATE INDEX IF NOT EXISTS idx_complaints_user_id ON complaints(user_id);
    CREATE INDEX IF NOT EXISTS idx_complaints_status ON complaints(status);
    CREATE INDEX IF NOT EXISTS idx_complaint_responses_complaint_id ON complaint_responses(complaint_id);
    CREATE INDEX IF NOT EXISTS idx_complaint_status_history_complaint_id ON complaint_status_history(complaint_id);

    -- Enable RLS
    ALTER TABLE complaints ENABLE ROW LEVEL SECURITY;
    ALTER TABLE complaint_responses ENABLE ROW LEVEL SECURITY;
    ALTER TABLE complaint_status_history ENABLE ROW LEVEL SECURITY;

    -- Enable RLS for profiles table
    ALTER TABLE IF EXISTS profiles ENABLE ROW LEVEL SECURITY;

    -- Drop existing profile policies if they exist
    SELECT EXISTS (
        SELECT 1 
        FROM pg_policies 
        WHERE tablename = 'profiles' AND policyname = 'users_can_update_own_profile'
    ) INTO policy_exists;
    
    IF policy_exists THEN
        DROP POLICY users_can_update_own_profile ON profiles;
    END IF;

    SELECT EXISTS (
        SELECT 1 
        FROM pg_policies 
        WHERE tablename = 'profiles' AND policyname = 'users_can_view_own_profile'
    ) INTO policy_exists;
    
    IF policy_exists THEN
        DROP POLICY users_can_view_own_profile ON profiles;
    END IF;

    -- Create profile policies
    CREATE POLICY users_can_view_own_profile ON profiles
        FOR SELECT USING (auth.uid()::text = id::text);

    CREATE POLICY users_can_update_own_profile ON profiles
        FOR UPDATE USING (auth.uid()::text = id::text);

    CREATE POLICY users_can_create_own_profile ON profiles
        FOR INSERT WITH CHECK (auth.uid()::text = id::text);

    -- Create profiles table without auth dependency
    CREATE TABLE IF NOT EXISTS profiles (
        id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
        name TEXT NOT NULL,
        phone_number TEXT NOT NULL,
        email TEXT,
        balance NUMERIC DEFAULT 0,
        data_balance NUMERIC DEFAULT 0,
        has_4g BOOLEAN DEFAULT false,
        created_at TIMESTAMPTZ DEFAULT NOW(),
        updated_at TIMESTAMPTZ DEFAULT NOW()
    );

    -- Insert default profile if not exists
    DO $$ 
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM profiles WHERE phone_number = '9866225000') THEN
            INSERT INTO profiles (name, phone_number, balance, data_balance)
            VALUES ('Laxman Regmi', '9866225000', 500, 0);
        END IF;
    END $$;

    -- Enable RLS but allow public access
    ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;

    -- Allow anyone to insert and view profiles
    CREATE POLICY allow_all_profiles ON profiles FOR ALL USING (true) WITH CHECK (true);

    -- Drop existing policies if they exist
    SELECT EXISTS (
        SELECT 1 
        FROM pg_policies 
        WHERE tablename = 'complaints' AND policyname = 'users_can_create_complaints'
    ) INTO policy_exists;
    
    IF policy_exists THEN
        DROP POLICY users_can_create_complaints ON complaints;
    END IF;

    SELECT EXISTS (
        SELECT 1 
        FROM pg_policies 
        WHERE tablename = 'complaints' AND policyname = 'users_can_view_own_complaints'
    ) INTO policy_exists;
    
    IF policy_exists THEN
        DROP POLICY users_can_view_own_complaints ON complaints;
    END IF;

    SELECT EXISTS (
        SELECT 1 
        FROM pg_policies 
        WHERE tablename = 'complaint_responses' AND policyname = 'users_can_view_own_complaint_responses'
    ) INTO policy_exists;
    
    IF policy_exists THEN
        DROP POLICY users_can_view_own_complaint_responses ON complaint_responses;
    END IF;

    SELECT EXISTS (
        SELECT 1 
        FROM pg_policies 
        WHERE tablename = 'complaint_status_history' AND policyname = 'users_can_view_own_complaint_history'
    ) INTO policy_exists;
    
    IF policy_exists THEN
        DROP POLICY users_can_view_own_complaint_history ON complaint_status_history;
    END IF;

    -- Create new policies
    CREATE POLICY users_can_create_complaints ON complaints
        FOR INSERT WITH CHECK (auth.uid()::text = user_id::text);

    CREATE POLICY users_can_view_own_complaints ON complaints
        FOR SELECT USING (auth.uid()::text = user_id::text);

    CREATE POLICY users_can_view_own_complaint_responses ON complaint_responses
        FOR SELECT USING (
            EXISTS (
                SELECT 1 FROM complaints 
                WHERE complaints.id = complaint_responses.complaint_id 
                AND complaints.user_id::text = auth.uid()::text
            )
        );

    CREATE POLICY users_can_view_own_complaint_history ON complaint_status_history
        FOR SELECT USING (
            EXISTS (
                SELECT 1 FROM complaints 
                WHERE complaints.id = complaint_status_history.complaint_id 
                AND complaints.user_id::text = auth.uid()::text
            )
        );

    -- Create triggers
    DROP TRIGGER IF EXISTS update_complaints_updated_at ON complaints;
    CREATE TRIGGER update_complaints_updated_at
        BEFORE UPDATE ON complaints
        FOR EACH ROW
        EXECUTE FUNCTION update_updated_at_column();

    DROP TRIGGER IF EXISTS record_complaint_status_change ON complaints;
    CREATE TRIGGER record_complaint_status_change
        AFTER UPDATE OF status ON complaints
        FOR EACH ROW
        EXECUTE FUNCTION record_complaint_status_change();
END;
$$ LANGUAGE plpgsql;

-- Function to submit a complaint
CREATE OR REPLACE FUNCTION submit_complaint(
    p_subject TEXT,
    p_description TEXT
)
RETURNS TABLE (id BIGINT, status complaint_status) 
SECURITY DEFINER
SET search_path = public
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    INSERT INTO complaints (user_id, subject, description)
    VALUES (auth.uid(), p_subject, p_description)
    RETURNING complaints.id, complaints.status;
END;
$$;

-- Function to get complaints for current user
CREATE OR REPLACE FUNCTION get_my_complaints()
RETURNS TABLE (
    id BIGINT,
    created_at TIMESTAMPTZ,
    subject TEXT,
    description TEXT,
    status complaint_status,
    updated_at TIMESTAMPTZ
)
SECURITY DEFINER
SET search_path = public
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT c.id, c.created_at, c.subject, c.description, c.status, c.updated_at
    FROM complaints c
    WHERE c.user_id = auth.uid()
    ORDER BY c.created_at DESC;
END;
$$;

-- Function to get complaint details with responses and history
CREATE OR REPLACE FUNCTION get_complaint_details(p_complaint_id BIGINT)
RETURNS TABLE (
    id BIGINT,
    created_at TIMESTAMPTZ,
    subject TEXT,
    description TEXT,
    status complaint_status,
    updated_at TIMESTAMPTZ,
    responses JSON,
    status_history JSON
)
SECURITY DEFINER
SET search_path = public
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        c.id,
        c.created_at,
        c.subject,
        c.description,
        c.status,
        c.updated_at,
        COALESCE(
            (SELECT json_agg(row_to_json(r))
            FROM complaint_responses r
            WHERE r.complaint_id = c.id),
            '[]'::json
        ) as responses,
        COALESCE(
            (SELECT json_agg(row_to_json(h))
            FROM complaint_status_history h
            WHERE h.complaint_id = c.id),
            '[]'::json
        ) as status_history
    FROM complaints c
    WHERE c.id = p_complaint_id AND c.user_id = auth.uid();
END;
$$;

-- Function to update complaint status
CREATE OR REPLACE FUNCTION update_complaint_status(
    p_complaint_id BIGINT,
    p_new_status complaint_status
)
RETURNS TABLE (
    id BIGINT,
    status complaint_status,
    updated_at TIMESTAMPTZ
)
SECURITY DEFINER
SET search_path = public
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    UPDATE complaints
    SET status = p_new_status
    WHERE id = p_complaint_id AND user_id = auth.uid()
    RETURNING complaints.id, complaints.status, complaints.updated_at;
END;
$$;